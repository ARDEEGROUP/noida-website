				<p>Ardee calls its teachers mentors, and in the Houses the word is exact. Our trained and certified Montessori educators guide each child with patience, deep observation, and a thorough understanding of early-years development. They support growth through gentle guidance rather than instruction: a presentation is given once, precisely and slowly, and then the child is left to work.</p>
