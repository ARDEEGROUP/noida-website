			<div class="prose">
				<p>In the final year of the House, Montessori work is mapped to the Early Years Foundation Stage (EYFS), the framework that describes what young children should experience across three prime areas of learning and four specific areas. The prime areas are communication and language, physical development, and personal, social and emotional development. The specific areas are literacy, mathematics, understanding the world, and expressive arts and design.</p>
