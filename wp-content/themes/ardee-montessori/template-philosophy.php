			<div class="head"><div class="eyebrow">The method</div><h2 class="title">A century of <em>evidence</em>.</h2></div>
			<div class="prose">
				<p>Dr. Maria Montessori was a physician before she was an educator. The first Casa dei Bambini, the Children's House, opened in Rome in 1907, and the method that grew from it rests on a single observation that she repeated across cultures and decades: given a carefully prepared environment and the freedom to work within it, the young child builds intelligence, character and self-discipline from the inside. Her principle of the planes of development describes childhood as a sequence of distinct stages, each with its own sensitivities and its own way of learning.</p>
				<p>The first plane, from birth to about six years, is the period of the absorbent mind. The child does not study the world; the child absorbs it, taking in language, movement, order and culture through direct experience. Everything in a Montessori House is arranged in response to this fact. Materials are real and precisely made. Furniture is scaled to the child. Time is given in long, uninterrupted stretches. The adult observes first and intervenes last.</p>
				<p>In 1929 Dr. Montessori founded the Association Montessori Internationale (AMI) to protect the integrity of her work. The Ardee Montessori Houses use internationally standardised Montessori apparatus and follow the method as she set it down, without dilution: the "Pure Montessori" of the Ardee continuum.</p>
